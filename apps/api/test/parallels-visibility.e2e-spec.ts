import type { NestFastifyApplication } from '@nestjs/platform-fastify';
import request from 'supertest';
import { randomUUID } from 'node:crypto';
import { createTestApp, getHttpServer } from './utils/create-test-app.js';
import { PrismaService } from '../src/database/prisma.service.js';
import { EmergingParallelService } from '../src/modules/identity-engine/emerging-parallel.service.js';

describe('Parallels Ghost Mode & Visibility (e2e)', () => {
  let app: NestFastifyApplication;
  let prisma: PrismaService;
  let emergingParallelService: EmergingParallelService;

  const createdEmails: string[] = [];
  const createdParallelTypeIds: string[] = [];

  beforeAll(async () => {
    app = await createTestApp();
    prisma = app.get(PrismaService);
    emergingParallelService = app.get(EmergingParallelService);
  });

  afterAll(async () => {
    if (createdEmails.length > 0) {
      await prisma.user.deleteMany({
        where: { email: { in: createdEmails } },
      });
    }
    if (createdParallelTypeIds.length > 0) {
      await prisma.parallelType.deleteMany({
        where: { id: { in: createdParallelTypeIds } },
      });
    }
    await app.close();
  });

  async function signupAndCompleteOnboarding() {
    const suffix = randomUUID().slice(0, 8);
    const email = `e2e-vis-${suffix}@example.com`;
    const username = `vis_${suffix}`;
    createdEmails.push(email);

    const signupRes = await request(getHttpServer(app))
      .post('/v1/auth/signup')
      .send({ email, username, password: 'password123' });

    expect(signupRes.status).toBe(201);
    const accessToken: string = signupRes.body.data.accessToken;
    const userId: string = signupRes.body.data.user.id;

    // Fetch real onboarding questions and submit all 4 answers over HTTP
    const questionsRes = await request(getHttpServer(app))
      .get('/v1/onboarding/questions')
      .set('Authorization', `Bearer ${accessToken}`);

    expect(questionsRes.status).toBe(200);
    expect(Array.isArray(questionsRes.body)).toBe(true);
    expect(questionsRes.body.length).toBeGreaterThanOrEqual(4);

    for (const question of questionsRes.body as Array<{
      key: string;
      options: Array<{ value: string }>;
    }>) {
      const answerRes = await request(getHttpServer(app))
        .post('/v1/onboarding/answers')
        .set('Authorization', `Bearer ${accessToken}`)
        .send({
          questionKey: question.key,
          answerValue: question.options[0].value,
        });

      expect(answerRes.status).toBe(204);
    }

    // Complete onboarding over HTTP — generates the 4 initial starter Parallels
    const completeRes = await request(getHttpServer(app))
      .post('/v1/onboarding/complete')
      .set('Authorization', `Bearer ${accessToken}`);

    expect(completeRes.status).toBe(201);

    return {
      userId,
      username,
      accessToken,
      initialMap: completeRes.body as {
        user: { id: string; username: string };
        parallels: Array<{
          id: string;
          isGhost: boolean;
          isHidden: boolean;
          parallelType: { id: string; name: string };
        }>;
      },
    };
  }

  it('publishes the 4 initial starter Parallels during onboarding and keeps emerging Parallels private until published by their owner', async () => {
    const userA = await signupAndCompleteOnboarding();
    const userB = await signupAndCompleteOnboarding();

    // 1. All 4 starter Parallels generated by onboarding start PUBLIC (isGhost: false)
    expect(userA.initialMap.parallels).toHaveLength(4);
    for (const starter of userA.initialMap.parallels) {
      expect(starter.isGhost).toBe(false);
      expect(starter.isHidden).toBe(false);
    }

    // Public profile immediately exposes User A's 4 starter Parallels
    const publicProfileBefore = await request(getHttpServer(app))
      .get(`/v1/users/${userA.userId}/parallels`)
      .set('Authorization', `Bearer ${userB.accessToken}`);

    expect(publicProfileBefore.status).toBe(200);
    expect(publicProfileBefore.body.data).toHaveLength(4);

    // People discovery immediately finds User A for a shared starter Parallel
    const starterParallelTypeId = userA.initialMap.parallels[0].parallelType.id;
    const starterPeopleRes = await request(getHttpServer(app))
      .get(`/v1/parallels/${starterParallelTypeId}/people`)
      .set('Authorization', `Bearer ${userB.accessToken}`);

    expect(starterPeopleRes.status).toBe(200);
    const starterUserIds = (
      starterPeopleRes.body as Array<{ user: { id: string } }>
    ).map((entry) => entry.user.id);
    expect(starterUserIds).toContain(userA.userId);

    // 2. Newly emerging Parallels created by EmergingParallelService remain GHOST (isGhost: true)
    const unitVector = Array.from({ length: 384 }, (_, idx) =>
      idx === 0 ? 1 : 0,
    );
    const uniqueSuffix = randomUUID().slice(0, 6);

    const emergingOne = await emergingParallelService.createEmergingParallel(
      userA.userId,
      {
        name: `Urban Explorer ${uniqueSuffix}`,
        description: 'Drawn to cities and street architecture.',
        icon: 'compass',
        strengthPct: 19,
        suggestionReason: 'Emerged from your recent city saves.',
        embedding: unitVector,
      },
    );
    createdParallelTypeIds.push(emergingOne.parallelTypeId);

    const emergingTwo = await emergingParallelService.createEmergingParallel(
      userA.userId,
      {
        name: `Analog Synth ${uniqueSuffix}`,
        description: 'Experimenting with modular sound design.',
        icon: 'music',
        strengthPct: 15,
        suggestionReason: 'Emerged from your late-night synth bookmarks.',
        embedding: unitVector,
      },
    );
    createdParallelTypeIds.push(emergingTwo.parallelTypeId);

    // Owner sees both emerging Parallels as Ghost on their map
    const mapBeforePublish = await request(getHttpServer(app))
      .get('/v1/parallels/map')
      .set('Authorization', `Bearer ${userA.accessToken}`);

    expect(mapBeforePublish.status).toBe(200);
    const mapParallelsBefore = mapBeforePublish.body.parallels as Array<{
      id: string;
      isGhost: boolean;
    }>;
    expect(
      mapParallelsBefore.find((p) => p.id === emergingOne.userParallelId)
        ?.isGhost,
    ).toBe(true);
    expect(
      mapParallelsBefore.find((p) => p.id === emergingTwo.userParallelId)
        ?.isGhost,
    ).toBe(true);

    // Ghost Parallels are NOT visible on public profile or in people discovery
    const publicProfileWithGhosts = await request(getHttpServer(app))
      .get(`/v1/users/${userA.userId}/parallels`)
      .set('Authorization', `Bearer ${userB.accessToken}`);

    expect(publicProfileWithGhosts.status).toBe(200);
    expect(publicProfileWithGhosts.body.data).toHaveLength(4);

    const peopleBeforePublish = await request(getHttpServer(app))
      .get(`/v1/parallels/${emergingOne.parallelTypeId}/people`)
      .set('Authorization', `Bearer ${userB.accessToken}`);

    expect(peopleBeforePublish.status).toBe(200);
    expect(
      (peopleBeforePublish.body as Array<{ user: { id: string } }>).some(
        (entry) => entry.user.id === userA.userId,
      ),
    ).toBe(false);

    // 3. Unauthenticated request is rejected with 401
    const unauthRes = await request(getHttpServer(app)).post(
      `/v1/parallels/${emergingOne.userParallelId}/make-public`,
    );
    expect(unauthRes.status).toBe(401);

    // 4. Non-owner (User B) attempting to publish User A's Ghost Parallel is rejected with 403
    const forbiddenRes = await request(getHttpServer(app))
      .post(`/v1/parallels/${emergingOne.userParallelId}/make-public`)
      .set('Authorization', `Bearer ${userB.accessToken}`);

    expect(forbiddenRes.status).toBe(403);

    const stillGhostRow = await prisma.userParallel.findUnique({
      where: { id: emergingOne.userParallelId },
    });
    expect(stillGhostRow?.isGhost).toBe(true);

    // 5. Invalid Parallel ID returns 404
    const notFoundRes = await request(getHttpServer(app))
      .post('/v1/parallels/non-existent-parallel-id/make-public')
      .set('Authorization', `Bearer ${userA.accessToken}`);

    expect(notFoundRes.status).toBe(404);

    // 6. Owner (User A) publishes emergingOne — only emergingOne changes to isGhost: false
    const publishRes = await request(getHttpServer(app))
      .post(`/v1/parallels/${emergingOne.userParallelId}/make-public`)
      .set('Authorization', `Bearer ${userA.accessToken}`);

    expect(publishRes.status).toBe(200);
    expect(publishRes.body.id).toBe(emergingOne.userParallelId);
    expect(publishRes.body.isGhost).toBe(false);
    expect(publishRes.body.isHidden).toBe(false);
    expect(publishRes.body.parallelType.id).toBe(emergingOne.parallelTypeId);

    // Second Ghost Parallel remains private (untouched)
    const untouchedRow = await prisma.userParallel.findUnique({
      where: { id: emergingTwo.userParallelId },
    });
    expect(untouchedRow?.isGhost).toBe(true);

    // Published emerging Parallel now appears on User A's public profile and in people discovery
    const publicProfileAfterPublish = await request(getHttpServer(app))
      .get(`/v1/users/${userA.userId}/parallels`)
      .set('Authorization', `Bearer ${userB.accessToken}`);

    expect(publicProfileAfterPublish.status).toBe(200);
    const visibleTypeIds = (
      publicProfileAfterPublish.body.data as Array<{
        parallelType: { id: string };
      }>
    ).map((p) => p.parallelType.id);
    expect(visibleTypeIds).toContain(emergingOne.parallelTypeId);
    expect(visibleTypeIds).not.toContain(emergingTwo.parallelTypeId);

    const peopleAfterPublish = await request(getHttpServer(app))
      .get(`/v1/parallels/${emergingOne.parallelTypeId}/people`)
      .set('Authorization', `Bearer ${userB.accessToken}`);

    expect(peopleAfterPublish.status).toBe(200);
    expect(
      (peopleAfterPublish.body as Array<{ user: { id: string } }>).some(
        (entry) => entry.user.id === userA.userId,
      ),
    ).toBe(true);

    // 7. Re-publishing an already-public Parallel is idempotent
    const idempotentRes = await request(getHttpServer(app))
      .post(`/v1/parallels/${emergingOne.userParallelId}/make-public`)
      .set('Authorization', `Bearer ${userA.accessToken}`);

    expect(idempotentRes.status).toBe(200);
    expect(idempotentRes.body.id).toBe(emergingOne.userParallelId);
    expect(idempotentRes.body.isGhost).toBe(false);

    // 8. Hiding emergingTwo excludes it from owner's map without conflating Ghost and Hidden
    const hideRes = await request(getHttpServer(app))
      .patch(`/v1/parallels/${emergingTwo.userParallelId}/hide`)
      .set('Authorization', `Bearer ${userA.accessToken}`);

    expect(hideRes.status).toBe(200);

    const hiddenRow = await prisma.userParallel.findUnique({
      where: { id: emergingTwo.userParallelId },
    });
    expect(hiddenRow?.isHidden).toBe(true);
    expect(hiddenRow?.isGhost).toBe(true);
  });
});
